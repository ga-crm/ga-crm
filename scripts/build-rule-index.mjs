// Generates docs/requirements from requirement/*.md (spec v2.1). Run: npm run docs:rules (add --check to verify only).
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const specDir = join(root, 'requirement');
const outDir = join(root, 'docs/requirements');
const check = process.argv.includes('--check');

const DOMAINS = {
  TEN: 'Cô lập tenant',
  SCOPE: 'Phạm vi theo cây đại lý',
  PDP: 'Bảo vệ dữ liệu cá nhân',
  AUD: 'Kiểm toán',
  DATA: 'Quy ước dữ liệu',
  UI: 'Ngôn ngữ và giao diện',
  ROLE: 'Vai trò',
  PERM: 'Quyền hạn',
  TENANT: 'Quản lý GA',
  OPT: 'Danh mục lead',
  PRG: 'Danh mục chương trình bảo hiểm',
  USER: 'Người dùng, lời mời, xác thực',
  AGT: 'Cây đại lý',
  LEAD: 'Quy trình lead',
  NOTE: 'Nhật ký tương tác',
  CMT: 'Góp ý của quản lý',
  TASK: 'Việc cần làm và lịch',
  CUS: 'Khách hàng 360',
  MAN: 'Nhập tay khách hàng',
  POL: 'Nhập tay hợp đồng',
  PRD: 'Chương trình trên hợp đồng',
  ASG: 'Phân công khách hàng',
  FAM: 'Gia đình',
  COV: 'Quyền lợi bảo hiểm',
  SIG: 'Cơ hội chăm sóc',
  CMP: 'Chiến dịch và biểu mẫu công khai',
  IMP: 'Nhập dữ liệu',
  RPT: 'Báo cáo và xuất dữ liệu',
  AI: 'Trợ lý AI',
  NTF: 'Thông báo',
};

const RULE_LINE = /^\s*(?:[-*]\s+)?\*\*([A-Z]{2,6}-\d+[a-z]?)\*\*/;
const BOLD_ID = /\*\*([A-Z]{2,6}-\d+[a-z]?)\*\*/g;
const specFiles = readdirSync(specDir).filter((name) => name.endsWith('.md')).sort();

const rules = [];
const sections = [];
let boldIds = 0;

for (const name of specFiles) {
  const lines = readFileSync(join(specDir, name), 'utf8').split('\n');
  lines.forEach((line, index) => {
    boldIds += [...line.matchAll(BOLD_ID)].filter((match) => match[1].split('-')[0] in DOMAINS).length;

    const heading = line.match(/^(#{1,3}) (.+)/);
    if (heading && index > 0) sections.push({ depth: heading[1].length, title: heading[2], source: `requirement/${name}:${index + 1}` });

    const rule = line.match(RULE_LINE);
    if (!rule || !(rule[1].split('-')[0] in DOMAINS)) return;

    // Indented lines below a rule (sub-bullets, tables) belong to it
    const body = [line.trim()];
    for (let next = index + 1; next < lines.length; next++) {
      if (!/^\s+\S/.test(lines[next]) || RULE_LINE.test(lines[next])) break;
      body.push(lines[next].trimEnd());
    }
    rules.push({ id: rule[1], domain: rule[1].split('-')[0], source: `requirement/${name}:${index + 1}`, body: body.join('\n') });
  });
}

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : /\.tsx?$/.test(name) ? [path] : [];
  });
}

// requirement/27 and README: code and tests cite the rule they implement
const citations = new Map();
for (const file of ['backend/src', 'backend/test', 'frontend/src'].flatMap((dir) => walk(join(root, dir)))) {
  for (const match of readFileSync(file, 'utf8').matchAll(/\b([A-Z]{2,6}-\d+)\b/g)) {
    if (!citations.has(match[1])) citations.set(match[1], new Set());
    citations.get(match[1]).add(relative(root, file));
  }
}

const NOTICE = '<!-- Generated by scripts/build-rule-index.mjs. Do not edit: run npm run docs:rules -->';
const output = new Map();
const domains = Object.keys(DOMAINS);

for (const domain of domains) {
  const own = rules.filter((rule) => rule.domain === domain);
  const parts = [NOTICE, `# ${domain}: ${DOMAINS[domain]}`, `${own.length} quy tắc, trích nguyên văn từ đặc tả.`];
  for (const rule of own) {
    const files = [...(citations.get(rule.id) ?? [])].sort();
    const status = files.length ? `Đã trích dẫn trong: ${files.map((file) => `\`${file}\``).join(', ')}` : 'Chưa có trong code';
    parts.push(`## ${rule.id}\n\nNguồn: \`${rule.source}\`\n\n${status}\n\n${rule.body}`);
  }
  output.set(`rules/${domain}.md`, `${parts.join('\n\n')}\n`);
}

const cited = (domain) => rules.filter((rule) => rule.domain === domain && citations.has(rule.id)).length;
const rows = domains.map((domain) => {
  const total = rules.filter((rule) => rule.domain === domain).length;
  return `| [${domain}](rules/${domain}.md) | ${DOMAINS[domain]} | ${total} | ${cited(domain)} |`;
});
const totalCited = rules.filter((rule) => citations.has(rule.id)).length;

output.set(
  'INDEX.md',
  `${[
    NOTICE,
    '# Chỉ mục đặc tả',
    `Tổng cộng ${rules.length} quy tắc, ${totalCited} quy tắc đã được trích dẫn trong code. "Đã trích dẫn" chỉ nghĩa là code hoặc test có nhắc mã quy tắc, không có nghĩa là đã làm đủ. Phần còn thiếu xem \`docs/ROADMAP.md\` và \`docs/decisions.md\`.`,
    '## Quy tắc theo miền',
    '| Mã | Miền | Số quy tắc | Đã trích dẫn |\n|---|---|---|---|\n' + rows.join('\n'),
    '## Bản đồ mục lục',
    sections.map(({ depth, title, source }) => `${'  '.repeat(depth - 1)}- ${title} (\`${source}\`)`).join('\n'),
  ].join('\n\n')}\n`,
);

if (boldIds !== rules.length) {
  console.warn(`Warning: spec has ${boldIds} bold rule ids but ${rules.length} were extracted as rules.`);
}

if (check) {
  const stale = [...output].filter(([path, content]) => {
    const file = join(outDir, path);
    return !existsSync(file) || readFileSync(file, 'utf8') !== content;
  });
  if (stale.length) {
    console.error(`Out of date: ${stale.map(([path]) => path).join(', ')}. Run npm run docs:rules`);
    process.exit(1);
  }
  console.log('docs/requirements is up to date.');
} else {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(join(outDir, 'rules'), { recursive: true });
  for (const [path, content] of output) writeFileSync(join(outDir, path), content);
  console.log(`Wrote ${output.size} files: ${rules.length} rules, ${totalCited} cited in code.`);
}
